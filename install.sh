#!/bin/zsh
# Build and install everything from a source checkout:
#   ~/Applications/SendToMyBot.app, the sender CLI, and the relay LaunchAgent.
# Safe to re-run. (Homebrew users: `brew install grynn/tap/send-to-my-bot`
# then `send-to-my-bot setup` — this script is the from-source equivalent.)
set -euo pipefail

APP_NAME="SendToMyBot"
ROOT="$(cd "$(dirname "$0")" && pwd)"
INSTALLED="$HOME/Applications/$APP_NAME.app"
SUPPORT="$HOME/Library/Application Support/$APP_NAME"
SHIM="$HOME/.local/bin/send-to-my-bot"

UV="$(command -v uv 2>/dev/null || true)"
for candidate in "$HOME/.local/bin/uv" /opt/homebrew/bin/uv /usr/local/bin/uv; do
    [[ -n "$UV" ]] && break
    [[ -x "$candidate" ]] && UV="$candidate"
done
[[ -n "$UV" ]] || { echo "uv not found — install from https://astral.sh/uv"; exit 1; }

"$ROOT/scripts/build.sh" "$ROOT/build"

echo "== installing $INSTALLED"
mkdir -p "$HOME/Applications"
rm -rf "$INSTALLED"
cp -R "$ROOT/build/$APP_NAME.app" "$INSTALLED"

echo "== installing sender + CLI shim"
mkdir -p "$SUPPORT" "$(dirname "$SHIM")"
cp "$ROOT/sender/bot_send.py" "$SUPPORT/bot_send.py"
cp "$ROOT/agent/relay.plist.template" "$SUPPORT/relay.plist.template"
cat > "$SHIM" <<SHIM_EOF
#!/bin/sh
# Generated by $APP_NAME install.sh
case "\$1" in
    setup)   exec "$ROOT/scripts/register.sh" --app "$INSTALLED" --script "$SUPPORT/bot_send.py" --uv "$UV" ;;
    unsetup) exec "$ROOT/scripts/unregister.sh" --app "$INSTALLED" ;;
esac
exec "$UV" run "$SUPPORT/bot_send.py" "\$@"
SHIM_EOF
chmod +x "$SHIM"

"$ROOT/scripts/register.sh" --app "$INSTALLED" --script "$SUPPORT/bot_send.py" --uv "$UV"
echo "Done. CLI: $SHIM"
